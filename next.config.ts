import type { NextConfig } from "next";

// Content-Security-Policy. Pages are prerendered, so no per-request nonce exists and
// script-src keeps 'unsafe-inline' for Next's hydration scripts and JSON-LD. Third parties:
//   - va.vercel-scripts.com / vitals.vercel-insights.com: Vercel Analytics + Speed Insights
//   - googletagmanager.com / google-analytics.com: GA4, loaded only after consent
//   - cdn.sanity.io: CMS content
const contentSecurityPolicy = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' https://va.vercel-scripts.com https://www.googletagmanager.com",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https://cdn.sanity.io https://*.google-analytics.com https://www.googletagmanager.com",
  "font-src 'self'",
  "connect-src 'self' https://vitals.vercel-insights.com https://va.vercel-scripts.com https://cdn.sanity.io https://*.google-analytics.com https://*.analytics.google.com https://www.googletagmanager.com",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "upgrade-insecure-requests",
].join("; ");

